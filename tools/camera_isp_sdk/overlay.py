"""Device tree overlays.

A sensor provides one fragment (sensors/<id>/overlay.dtsi) written against
the CAM_* port macros; the board provides a header per camera connector and
the shared receiver plumbing (boards/<board>/camera-port.dtsi). This module
glues them into one overlay per (sensor, port) and compiles it with the C
preprocessor and dtc, the same way the kernel builds .dtso files.
"""

import shutil
import subprocess
from pathlib import Path

from . import __version__


class OverlayError(Exception):
    pass


def wrapper_source(root, board, sensor, port):
    name = board.overlay_name(port, sensor.id)
    lines = [
        "// SPDX-License-Identifier: GPL-2.0",
        f"// {name}.dtso: generated by camera-isp-sdk {__version__}, do not edit.",
        f"// Sensor: {sensor.name} ({sensor.overlay.relative_to(root)})",
        f"// Port:   {board.ports[port].description}",
        "",
        "/dts-v1/;",
        "/plugin/;",
        "",
        "#include <dt-bindings/gpio/gpio.h>",
        f'#include "{board.ports[port].header}"',
        '#include <camera-isp-sdk/camera.h>',
        "",
        f'#include "{sensor.overlay}"',
        "",
        f'#include "{board.dir / "camera-port.dtsi"}"',
        "",
        "&{/chosen} {",
        "\toverlays {",
        f'\t\t{name}.kernel = "camera-isp-sdk {__version__}";',
        "\t};",
        "};",
        "",
    ]
    return "\n".join(lines)


def _run(cmd, **kwargs):
    try:
        return subprocess.run(cmd, check=True, capture_output=True, text=True, **kwargs)
    except FileNotFoundError:
        raise OverlayError(f"{cmd[0]} not found; install cpp and device-tree-compiler") from None
    except subprocess.CalledProcessError as e:
        raise OverlayError(f"{' '.join(cmd[:2])} failed:\n{e.stderr}") from None


def build(root, board, sensor, port, out_dir):
    if port not in board.ports:
        raise OverlayError(f"{board.id} has no port '{port}' (ports: {', '.join(board.ports)})")
    if not sensor.overlay.is_file():
        raise OverlayError(f"{sensor.overlay} does not exist")
    if not board.ports[port].header.is_file():
        raise OverlayError(f"{board.ports[port].header} ({port} header of {board.id}) does not exist")

    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    name = board.overlay_name(port, sensor.id)
    dtso = out_dir / f"{name}.dtso"
    pre = out_dir / f"{name}.dts.tmp"
    dtbo = out_dir / f"{name}.dtbo"

    dtso.write_text(wrapper_source(root, board, sensor, port))
    _run(["cpp", "-nostdinc", "-undef", "-D__DTS__", "-x", "assembler-with-cpp",
          "-I", str(root / "include"), "-o", str(pre), str(dtso)])
    _run(["dtc", "-@", "-q", "-I", "dts", "-O", "dtb", "-o", str(dtbo), str(pre)])
    pre.unlink()
    return dtbo


def check_apply(base_dtb, dtbos, out_dtb):
    """Applies overlays to a base DTB with fdtoverlay, as U-Boot would."""
    if shutil.which("fdtoverlay") is None:
        raise OverlayError("fdtoverlay not found; install device-tree-compiler")
    _run(["fdtoverlay", "-i", str(base_dtb), "-o", str(out_dtb), *map(str, dtbos)])
    return out_dtb
